"""Infer a list transformation from examples and verify it before returning code."""

import re

SYSTEM = (
    "You are an expert at inferring small deterministic Python programs from examples. "
    "Prefer simple general rules over memorization. Pay close attention to ordering, "
    "duplicates, negative numbers, index versus value, and empty inputs."
)


def extract(text):
    blocks = re.findall(r"```(?:python|py)?\s*\n(.*?)```", text, re.DOTALL | re.IGNORECASE)
    if blocks:
        return blocks[-1].strip()
    match = re.search(r"(?m)^(?:import |from |def f\s*\()", text)
    return text[match.start():].strip() if match else text.strip()


def solve(task, api):
    examples = "\n".join(
        f"f({ex['input']!r}) == {ex['output']!r}" for ex in task["examples"]
    )
    prompt = (
        "Infer the intended transformation and implement def f(xs), returning a list "
        "of integers. All examples are generated by one general rule; hidden inputs "
        "will differ. Do not hardcode examples.\n\n"
        + examples
        + "\n\nConsider multiple plausible rules before choosing one. Investigate "
        "filtering, arithmetic transformations, sorting, positional operations and "
        "cumulative or neighboring values where appropriate. Distinguish rules that "
        "coincide on some examples. Match the exact output order and multiplicity. "
        "Handle empty and short inputs and negative values. Use only the standard "
        "library. Return only executable code in a Python code block."
    )
    code = ""
    for attempt in range(3):
        try:
            reply = api.llm(prompt, system=SYSTEM)
        except api.BudgetExceeded:
            break
        candidate = extract(reply)
        if candidate:
            code = candidate
        try:
            report = api.check(code)
        except api.BudgetExceeded:
            break
        failed = [r for r in report if not r["passed"]]
        if not failed:
            return code
        details = "\n".join(
            f"f({r['input']!r}) returned {r['actual']!r}; expected {r['expected']!r}"
            for r in failed
        )
        prompt += (
            "\n\nThe previous implementation was:\n```python\n" + code
            + "\n```\nIt failed these shown examples:\n" + details
            + "\nReconsider the underlying rule, not just these specific inputs. "
            "Return a complete corrected implementation."
        )
    return code
